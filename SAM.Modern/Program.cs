using SamModern.UI;
using SamModern.Web;
using SamModern.Workers;

namespace SamModern
{
    /// <summary>
    /// Entry point. The application is ONE executable that plays three roles, selected by its command line:
    /// <list type="bullet">
    /// <item><c>(no arguments)</c> - the normal app: starts the local web server (<see cref="ApiHost"/>) and shows a
    /// window (<see cref="MainForm"/>) that hosts the WebView2 user interface.</item>
    /// <item><c>--serve [--port N] [--token T]</c> - web server only, no window. Meant for development: the UI can then
    /// be opened and tested in any browser at <c>http://127.0.0.1:N/#t=T</c>.</item>
    /// <item><c>--api library|game &lt;appId&gt;</c> - a short-lived WORKER child process that talks to the Steam client
    /// (see <see cref="WorkerMain"/>). The Steam API can only act as ONE game per user, and a hung Steam call must not
    /// take the whole app down, so every Steam conversation lives in its own process.</item>
    /// </list>
    /// </summary>
    internal static class Program
    {
        /// <summary>
        /// An update may rename files that were still in use by a running copy of the app (e.g. "x.dll.old20261122105813").
        /// Once nothing uses them anymore they are removed here.
        /// </summary>
        private static void CleanUpOldFiles()
        {
            try
            {
                foreach (var file in Directory.EnumerateFiles(AppContext.BaseDirectory))
                {
                    if (System.Text.RegularExpressions.Regex.IsMatch(Path.GetFileName(file), @"\.old\d{14}$") == false) continue;
                    try { File.Delete(file); } catch (Exception) { /* still in use - next time */ }
                }
            }
            catch (Exception)
            {
            }
        }

        [STAThread]
        private static int Main(string[] args)
        {
            // Role 3: worker process. Handled first, before anything else is initialised.
            if (args.Length >= 1 && args[0] == "--api")
            {
                return WorkerMain.Run(args.Skip(1).ToArray());
            }

            CleanUpOldFiles();

            // Role 2 (dev server) needs a fixed port and token so a browser tab can reconnect after a restart.
            // In the normal app both are random per start (port 0 = let the OS pick, token generated by ApiHost).
            bool serveOnly = args.Contains("--serve");
            int port = 0;
            string token = null;
            for (int i = 0; i < args.Length - 1; i++)
            {
                if (args[i] == "--port") int.TryParse(args[i + 1], out port);
                if (args[i] == "--token") token = args[i + 1];
            }

            ApiHost host;
            try
            {
                host = ApiHost.StartAsync(serveOnly ? port : 0, serveOnly ? token : null).GetAwaiter().GetResult();
            }
            catch (Exception ex)
            {
                MessageBox.Show("The local server could not be started:\n\n" + ex.Message, "Steam Achievement Manager",
                    MessageBoxButtons.OK, MessageBoxIcon.Error);
                return 1;
            }

            // Never leave orphaned worker processes behind: each of them would keep "playing" a game in Steam.
            AppDomain.CurrentDomain.ProcessExit += (_, _) => WorkerProcess.KillAll();

            if (serveOnly)
            {
                Directory.CreateDirectory(Core.AppPaths.Root);
                File.WriteAllText(Path.Combine(Core.AppPaths.Root, "dev-url.txt"), host.UrlWithToken);
                new ManualResetEvent(false).WaitOne();
                return 0;
            }

            ApplicationConfiguration.Initialize();
            Application.Run(new MainForm(host));
            host.DisposeAsync().AsTask().GetAwaiter().GetResult();
            return 0;
        }
    }
}
